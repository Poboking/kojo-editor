/** 在清单 `ADAPTER_MANIFEST` 的数组结尾前插入一个条目块（其余字节不动） */
export function insertManifestEntry(source, block) {
  const anchor = source.indexOf('ADAPTER_MANIFEST');
  if (anchor < 0) throw new Error(MANIFEST_REL + ' 里找不到 ADAPTER_MANIFEST');
  // 从清单赋值号之后找**第一个**顶格 `];`：清单里的数组只有这一枚，后面的函数体不算
  const close = source.indexOf('\n];', anchor);
  if (close < 0) throw new Error(MANIFEST_REL + ' 里找不到 ADAPTER_MANIFEST 的数组结尾');
  return source.slice(0, close) + '\n' + block + source.slice(close + 1);
}

/** 在 app 依赖里插入一行（按键排序；空行/注释不受影响） */
export function insertAppDependency(source, packageName) {
  const lines = source.split('\n');
  const start = lines.findIndex((line) => /"dependencies"\s*:\s*\{/.test(line));
  if (start < 0) throw new Error(APP_PKG_REL + ' 里找不到 dependencies');
  const entry = '    "' + packageName + '": "workspace:*",';
  let insertAt = -1;
  for (let i = start + 1; i < lines.length; i += 1) {
    const match = lines[i].match(/^\s*"([^"]+)"\s*:/);
    if (match === null) continue;
    if (match[1] > packageName) {
      insertAt = i;
      break;
    }
  }
  if (insertAt < 0) {
    const closeAt = lines.findIndex((line, index) => index > start && /^\s*\}\s*,?\s*$/.test(line));
    if (closeAt < 0) throw new Error(APP_PKG_REL + ' 的 dependencies 没有闭合行');
    insertAt = closeAt;
  }
  lines.splice(insertAt, 0, entry);
  return lines.join('\n');
}

/** 在 tsconfig 的 `paths` 第一行后插入别名（JSONC：行尾标记合法） */
export function insertTsconfigPath(source, packageName, target) {
  const lines = source.split('\n');
  const start = lines.findIndex((line) => /"paths"\s*:\s*\{/.test(line));
  if (start < 0) throw new Error('tsconfig 里找不到 paths');
  lines.splice(start + 1, 0, '      "' + packageName + '": ["' + target + '"], // ' + MARKER);
  return lines.join('\n');
}

/** 在 vitest 的 `resolve.alias` 第一行后插入别名（TS：行尾标记合法） */
