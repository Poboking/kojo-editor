/** id 的合法形态：小写字母开头、纯小写字母数字（要拼进 TS 标识符与包名） */
const ID_PATTERN = /^[a-z][a-z0-9]{0,23}$/;
/** 扩展名：不带点的小写字母数字 */
const EXT_PATTERN = /^[a-z0-9]{1,16}$/;

/** 小写 id → PascalCase（`mygame` → `Mygame`） */
export function toPascal(id) {
  return id.charAt(0).toUpperCase() + id.slice(1);
}

/** 单引号 TS 字符串字面量（只转义反斜杠与单引号；换行由调用方先拒掉） */
function quote(text) {
  return "'" + text.replaceAll('\\', '\\\\').replaceAll("'", "\\'") + "'";
}

/** 校验参数；返回规范化后的方言描述（非法 ⇒ 抛错，错误信息给作者看） */
export function normalizeDialect({ id, title, ext }) {
  if (typeof id !== 'string' || !ID_PATTERN.test(id)) {
    throw new Error('--id 必须是 1–24 位小写字母/数字、以字母开头（要拼进包名与 TS 标识符，例：mygame）');
  }
  if (typeof title !== 'string' || title.trim().length === 0) {
    throw new Error('--title 不能为空（展示名，例："My Game"）');
  }
  if (/[\r\n]/.test(title)) throw new Error('--title 不能含换行');
  if (typeof ext !== 'string' || !EXT_PATTERN.test(ext)) {
    throw new Error('--ext 必须是不带点的小写字母/数字（例：kojo2）');
  }
  return Object.freeze({
    id,
    title: title.trim(),
    ext,
    dir: id + '-adapter',
    packageName: '@kojo/plugin-' + id + '-adapter',
    pascal: toPascal(id),
    constant: id.toUpperCase(),
  });
}

