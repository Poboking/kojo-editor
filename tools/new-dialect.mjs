function read(root, rel) {
  return readFileSync(path.join(root, rel), 'utf8');
}

/**
 * 生成计划（**不落盘**）：文件内容 + 共享文件的插入结果 + 冲突清单。
 * 冲突非空时调用方必须拒绝执行（本函数不做任何写入）。
 */
export function planDialect(options) {
  const root = path.resolve(options.root ?? DEFAULT_ROOT);
  const ctx = normalizeDialect(options);
  const pluginDir = path.join(root, 'packages/plugins', ctx.dir);
  const conflicts = [];

  if (existsSync(pluginDir)) {
    conflicts.push('目录已存在：packages/plugins/' + ctx.dir);
  }

  const manifestRel = path.join('packages/plugins', ctx.dir, 'src/index.ts');
  if (existsSync(path.join(root, manifestRel))) {
    conflicts.push('入口已存在：' + manifestRel);
  }

  const manifestText = read(root, MANIFEST_REL);
  if (new RegExp('^\\s*id:\\s*' + quote(ctx.id) + ',', 'm').test(manifestText)) {
    conflicts.push('清单已有同 id 条目：' + ctx.id);
  }
  if (manifestText.includes(ctx.packageName)) {
    conflicts.push('清单里已有同包名条目：' + ctx.packageName);
  }

  if (conflicts.length > 0) {
    return { root, ctx, conflicts, files: [], edits: [] };
  }

  const files = [
    { rel: path.join('packages/plugins', ctx.dir, 'package.json'), text: packageJson(ctx) },
    { rel: path.join('packages/plugins', ctx.dir, 'src/index.ts'), text: indexSource(ctx) },
    { rel: path.join('packages/plugins', ctx.dir, 'src/adapter.ts'), text: adapterSource(ctx) },
    { rel: path.join('packages/plugins', ctx.dir, 'src/backend.ts'), text: backendSource(ctx) },
    { rel: path.join('packages/plugins', ctx.dir, 'src/plugin.ts'), text: pluginSource(ctx) },
    { rel: path.join('packages/plugins', ctx.dir, 'tests/purity.test.ts'), text: purityTestSource(ctx) },
    { rel: path.join('packages/plugins', ctx.dir, 'tests/adapter-shape.test.ts'), text: shapeTestSource(ctx) },
  ];

  const edits = [
    {
      rel: MANIFEST_REL,
      text: insertManifestEntry(manifestText, manifestEntryBlock(ctx)),
      note: '清单条目块（// new-dialect）',
    },
    {
      rel: APP_PKG_REL,
      text: insertAppDependency(read(root, APP_PKG_REL), ctx.packageName),
      note: '依赖行（workspace:*；清单自证要求）',
    },
    {
      rel: ROOT_TSCONFIG_REL,
      text: insertTsconfigPath(read(root, ROOT_TSCONFIG_REL), ctx.packageName, './packages/plugins/' + ctx.dir + '/src/index.ts'),
      note: '路径别名（root tsc）',
    },
    {
      rel: APP_TSCONFIG_REL,
      text: insertTsconfigPath(read(root, APP_TSCONFIG_REL), ctx.packageName, '../plugins/' + ctx.dir + '/src/index.ts'),
      note: '路径别名（app tsc）',
    },
    {
      rel: VITEST_REL,
      text: insertVitestAlias(read(root, VITEST_REL), ctx.packageName, './packages/plugins/' + ctx.dir + '/src/index.ts'),
      note: '路径别名（vitest；必须与 root tsc 同集）',
    },
  ];

  return { root, ctx, conflicts, files, edits };
}

/** 计划 → 人话（`--dry-run` 与成功回执共用） */
export function formatPlan(plan) {
  const lines = [];
  if (plan.conflicts.length > 0) {
    lines.push('拒绝生成：');
    for (const item of plan.conflicts) lines.push('  ✗ ' + item);
    return lines.join('\n');
  }
  lines.push('方言：' + plan.ctx.id + '（' + plan.ctx.title + '，扩展名 .' + plan.ctx.ext + '）');
  lines.push('新建文件：');
  for (const file of plan.files) lines.push('  + ' + file.rel.replaceAll('\\', '/'));
  lines.push('共享文件插入（只加行）：');
  for (const edit of plan.edits) lines.push('  ~ ' + edit.rel.replaceAll('\\', '/') + ' — ' + edit.note);
  return lines.join('\n');
}

/**
 * 执行计划（只在冲突为空时写盘）。返回写入的相对路径清单。
 * 中途失败时不做回滚（磁盘不是事务）：按返回前缀 + 标记自行删除即可。
 */
export function applyPlan(plan) {
  if (plan.conflicts.length > 0) throw new Error('计划有冲突，拒绝落盘：\n' + formatPlan(plan));
  const written = [];
  for (const file of plan.files) {
    const abs = path.join(plan.root, file.rel);
    mkdirSync(path.dirname(abs), { recursive: true });
    writeFileSync(abs, file.text, 'utf8');
    written.push(file.rel);
  }
  for (const edit of plan.edits) {
    writeFileSync(path.join(plan.root, edit.rel), edit.text, 'utf8');
    written.push(edit.rel);
  }
  return written;
}

/* ---------------------------- CLI ---------------------------- */

function parseArgs(argv) {
  const out = { id: undefined, title: undefined, ext: undefined, dryRun: false, root: DEFAULT_ROOT };
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (token === '--dry-run') {
      out.dryRun = true;
      continue;
    }
    if (token === '--id' || token === '--title' || token === '--ext' || token === '--root') {
      const value = argv[i + 1];
      if (value === undefined || value.startsWith('--')) throw new Error('缺少 ' + token + ' 的值');
      i += 1;
      if (token === '--id') out.id = value;
      else if (token === '--title') out.title = value;
      else if (token === '--ext') out.ext = value;
      else out.root = value;
      continue;
    }
    if (token === '--help' || token === '-h') return { help: true };
    throw new Error('未知参数：' + token);
  }
  return out;
}

const USAGE = [
  '用法：node tools/new-dialect.mjs --id <小写短名> --title <显示名> --ext <扩展名> [--dry-run]',
  '',
  '生成 packages/plugins/<id>-adapter（最小可跑插件）+ adapter-manifest.ts 的一个条目块，',
  '并补上清单自证要求的依赖行与路径别名（全部带 // new-dialect 标记，便于删除）。',
  '--dry-run 只打印计划；同 id / 同目录 / 清单已有同项一律拒绝，不覆盖。',
  '--root <目录>（测试用）：在另一棵树上演练，默认仓库根。',
].join('\n');

function main(argv) {
  let parsed;
  try {
    parsed = parseArgs(argv);
  } catch (error) {
    console.error(String(error instanceof Error ? error.message : error));
    console.error(USAGE);
    return 2;
  }
  if (parsed.help) {
    console.log(USAGE);
    return 0;
  }
  if (parsed.id === undefined || parsed.title === undefined || parsed.ext === undefined) {
    console.error('缺少 --id / --title / --ext');
    console.error(USAGE);
    return 2;
  }

  let plan;
  try {
    plan = planDialect({ id: parsed.id, title: parsed.title, ext: parsed.ext, root: parsed.root });
  } catch (error) {
    console.error(String(error instanceof Error ? error.message : error));
    return 1;
  }

  if (plan.conflicts.length > 0) {
    console.error(formatPlan(plan));
    return 1;
  }

  if (parsed.dryRun) {
    console.log('[dry-run] 只打印计划，不落盘：');
    console.log(formatPlan(plan));
    return 0;
  }

  const written = applyPlan(plan);
  console.log('已生成方言 ' + plan.ctx.id + '：');
  for (const rel of written) console.log('  ' + rel.replaceAll('\\', '/'));
  console.log('');
  console.log('下一步：');
  console.log('  pnpm install   # 建 workspace 链接（运行期按包名解析；typecheck/vitest 走别名，不装也能过）');
  console.log('  node node_modules/vitest/vitest.mjs run packages/plugins/' + plan.ctx.dir + '/tests');
  console.log('  node tools/kojo-conformance.mjs language --adapter ' + plan.ctx.id);
  console.log('  pnpm typecheck && pnpm audit:decoupling');
  console.log('  写法见 docs/DIALECT-AUTHORING.md');
  return 0;
}

