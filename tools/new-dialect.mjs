/**
 * 新增一个方言 = **新增一个包 + 清单一行**（SDK B5a 的可扩展性判据）。
 *
 * 这个工具把「新增方言」从"照着某个 adapter 抄一遍、再记住六七个散点"降成一命令：
 *
 *   node tools/new-dialect.mjs --id mygame --title "My Game" --ext kojo2 [--dry-run]
 *
 * 生成（零依赖 Node，ESM）：
 * - `packages/plugins/<id>-adapter/`：最小可跑插件（v1 `Plugin` + 2.0 `GameAdapter` + 发射面）、
 *   自带 purity / 形态闸两份测试；
 * - `packages/app/src/adapter-manifest.ts`：**只插入一个条目块**（带 `// new-dialect` 标记）；
 * - 清单自证要求的散点：`packages/app/package.json` 的一行依赖（`workspace:*`）、
 *   root / app tsconfig 与 `vitest.config.ts` 各一行路径别名（都带标记）。
 *
 * 为什么散点也在本工具里改：`adapter-manifest.test.ts` 是**双向自证**——清单说有的，
 * 依赖/别名/磁盘必须真有。只加清单一行、把另外三处留给作者手改，正是该闸要防的
 * "漏一处不立刻红"；工具代劳后，作者的必改面真的只有「跑一条命令」。
 *
 * 纪律：
 * - **不覆盖**：同 id / 同目录 / 清单已有同项 ⇒ 非零退出并列出冲突，一个字节都不写；
 * - `--dry-run` 只打印计划；真正的 `applyPlan` 在全部冲突检查之后才落盘；
 * - 生成物**不含任何具体游戏名词**：id / title / ext 是作者给的方言名，引擎落点用
 *   `<ID>_FIRST` 这类由 id 派生的记号，事件目录只有共享用例认的那一条（`初见`）。
 *
 * 落盘顺序 = 先包目录、再配置文件：中途失败时按 `applyPlan` 返回的清单手工回退
 * （或直接删包 + 删带标记的行）。
 */
