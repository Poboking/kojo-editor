/**
 * ERB **引擎指令名全集**（4.981 语句面）—— 本项目里这张表的唯一真源。
 *
 * ## 出处（可复现，不是抄来的清单）
 *
 * 真源 = eratw `specs/engine-profiles.yaml` 的 `profiles.snake.commands`；快照在
 * `tools/data/engine-profiles.yaml`（EOL 归一化 sha256 `d9f0e025…`，逐字钉在
 * `instruction-names-contract.test.ts`）。每条由 `FunctionIdentifier.cs` 的
 * `addFunction(FunctionCode.X)` 静态注册表解析得到（快照 meta 记 Roslyn 独立复核），
 * `registration.snake.commands_unconditional = 324`。由
 * `node tools/gen-erb-instruction-names.mjs` 生成；判据双向对拍：新增不漏、假名不收。
 *
 * ## 为什么换口径（2026-11-28）
 *
 * 旧表取自 gitlab `EvilMask/emuera.em` master 的 `enum FunctionCode`：305 成员 − 4 = 301。
 * 枚举是**那条分支的**全集，不是 eraTW 实际跑的 4.981 语句面：snake 有 326 名
 * （324 无条件 + `VARI`/`VARS` 条件注册），旧表少 **23 个无条件词**。eraTW 4.981 真语料
 * 实测其中 13 名在用（共 103 处：`SETANIMETIMER` 30、`SETIMAGELAYERL` 20、`CALLSTR` 15、
 * `TINPUTSNF` 12、`BITMAP_CACHE_ENABLE` 7、`TRYCALLSTR` 6、`HTML_PRINTC` 5 …）。这些行此前
 * 在编辑器里是「引擎不认识的词」：进不了 `#DIM` 撞名检查、进不了状态回放的写指令短表、
 * 也不进补全。
 *
 * 条件注册两枚仍不收：`VARI`/`VARS` 由 `UseScopedVariableInstruction` 包住，eraTW 的
 * `emuera.config` 未开该开关（默认关）；eraSQC / eraSQN 的 `SYSTEM_DEBUG.ERB` 还把
 * `#DIMS VARS` 当私有变量名用且游戏能正常加载——收进来就是假缺陷。旁证：
 * `IdentifierDictionary.ThrowException` 里 `!UseScopedVariableInstruction &&
 * (idStr == "VARS" || idStr == "VARI")` ⇒ `CanNotUseVAR`（不开启时连用都不能用）。
 * 另：`__NULL__` 是空值哨兵、`SET` 不入 `funcDic`（代入文专用）、`OUTPUTLOG` 在枚举里被注释掉。
 *
 * ## 为什么不从 Era Wiki 的 excom 页抄
 *
 * 那页的标题是**交替式**（`PRINT(|V|S|FORM|FORMS)(|K|D)(|L|W)`、`PRINTBUTTON(|C|LC)` …），
 * 展开会造出引擎里并不存在的名字（如 `PRINTSW` 有、`PRINTKS` 无）。判据要的是
 * "这个名字会不会撞车"，过度近似的名字表只会换来假缺陷。
 *
 * ## 用途
 *
 * `declarations.ts` 的「`#DIM` 变量名不得与指令同名」——引擎侧是
 * `CheckUserVarName` / `CheckUserPrivateVarName` / `CheckUserMacroName` 三处的
 * `SystemInstrument` 分支（`warnLevel = 2` 后 `return`，即致命；`#DIM` 解析失败会让
 * 整个文件加载失败）。
 *
 * ## 不做
 *
 * 内建**式中函数**（exmeth）不在本表——那是 `builtins.ts` 的 `BUILTIN_SIGNATURES`
 * （引擎里是 `DefinedNameType.SystemMethod`，与本表同为致命档，但取数源不同）。
 * 两张表在规则处并集，各自维护自己的出处。
 */

