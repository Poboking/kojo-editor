/**
 * eraTW 4.980 漢化包 CSV 的**位表 / 位说明**策展数据。
 *
 * 「人工阅读 CSV 注释 + ERB 用法实证」筛出的机读位表，**纯数据、零 IO、冻结**。
 * 契约槽位见 `@kojo/plugin-api` 的 `VariableInfo.bits`
 * （`ReadonlyArray<{ bit: number; label: string }>`）；本文件是第一个产出方，
 * 由 `variable-schema.ts` 按 `(族:号)` 挂到 `lookup()` 的返回值上。
 *
 * 纪律：
 * - `label` 保留 CSV 注释**原文**，不翻译、不润色（全半角、错字、日文汉字一律照抄）。
 * - `bit` 为非负整数、同条目不重复、按 bit 升序。
 * - `source` 指向**注释行**位置（`CSV/<file>:<line>`，跨行用 `a-b`）；
 *   `evidence` 是该注释**整行原文**（一字不增删，跨行用 `\n`）—— 终审逐条按它核对。
 *
 * 判定口径（宁缺毋滥）：
 * - `bit-index`：注释带 `BIT` / `bit` / `ビット` 前缀且条目形如 `n=名` ⇒ `bit = n` **直取**。
 * - `bit-mask`：注释带同前缀但 `n` 连续翻倍（1,2,4,8…）⇒ 这是**掩码值不是位号**，
 *   换算 `bit = log2(n)`，`inferred = true`。当前仅 STAIN 一族属此形态（权威依据见其 note）。
 * - 无 bit 前缀的 `n=名` 序列**默认判「枚举值」不进表**；仅当 ERB 实证支持（实操位号落在
 *   该序列范围内）才升格 `bit-index`，并在 `note` 里注明 —— 本表 CFLAG:526 / FLAG:99 /
 *   TEQUIP:1 / TCVAR:143 四条即由此升格。
 * - 散文、范围说明、分组标题、被注释掉的变量定义行（如 `;37,固有料理`）、纯枚举一律 skip。
 *
 * 已知缺口（如实标注，补全**只给注释覆盖的位**、绝不猜缺位）：
 * - 注释覆盖位 ⊂ ERB 实用位：CFLAG:42（注释 0-8，实证仅位 8）、FLAG:999（注释 0-3，实用到 4/9/10）、
 *   FLAG:1026（注释到 13，实用到 14）、TFLAG:1（注释 1-9，实用到 26）、TALENT:2（注释 0/1，实用到 2）。
 * - `FLAG:51` 在 CSV 根目录**没有 `51,` 定义行**（数据保留，将来补定义行即生效）。
 * - `FLAG:1013` 是粘连形态（注释与名称列无分隔），`variable` 取名列首段。
 *
 * STAIN 的掩码换算有权威正证：`ERB/ステータス表示関連/INFO.ERB:225` 以循环变量
 * （`TYPE_STAIN` = 0..7）取位、`:228` 用 `GETBIT(STAIN:C_ID:BODY_PARTS, FINDELEMENT(STAIN_NAME, "巧克力"))`
 * —— 巧克力在 `STAIN_NAME` 里是第 8 项（位 7），与掩码 128 → bit 7 的换算吻合。
 * 语料里 `fromEN/_TR Lib.ERB:1406/1410/1416/1422` 把掩码值（64/8/4/1）当位号传，
 * 属**模组侧误用**，不构成换算反证（已记入对应条目的 note）。
 */

/** 单条策展位表。 */
export interface CuratedBitTable {
  /** 族名：CSV 文件名去扩展名并大写（如 `Talent.csv` → `TALENT`）。 */
  readonly family: string;
  /** 族内编号（源定义行首列原样）。 */
  readonly index: number;
  /** 变量名（源定义行第二列原文；无定义行时为 `''`）。 */
  readonly variable: string;
  /** 形态：位号直取 or 掩码换算。 */
  readonly form: 'bit-index' | 'bit-mask';
  /** 是否经 log2 换算（`form === 'bit-mask'` 时为 `true`）。 */
  readonly inferred: boolean;
  /** 注释行出处：`CSV/<file>:<line>`，跨行用 `a-b`。 */
  readonly source: string;
  /** 注释**整行原文**（一字不增删；跨行用 `\n` 连接）—— 终审的证据链。 */
  readonly evidence: string;
  /** ERB 侧用法实证摘记（命中位集合 + 算子计数；未命中注明）。 */
  readonly erbUsage: string;
  /** 该 `(族,号)` 是否在语料 ERB 层被实际读写。 */
  readonly usage: 'used' | 'unused';
  /** 冲突 / 粘连 / 缺定义 / 升格依据等需人工复核的点。 */
  readonly note?: string;
  /** 位条目（原文字面标签）。 */
  readonly bits: ReadonlyArray<{ readonly bit: number; readonly label: string }>;
}

