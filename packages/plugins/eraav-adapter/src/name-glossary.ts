/** 词典键按**长度降序**（同长保序）——与宿主 `ProjectView` 那把尺子逐字同口径。 */
const GLOSSARY_KEYS: readonly string[] = Object.keys(ERAAV_NAME_GLOSSARY).sort(
  (a, b) => b.length - a.length,
);

/**
 * 给日文名加「（中文）」对照后缀（纯函数；与 `eratw-adapter/src/name-glossary.ts:30-40` 同实现，
 * **不另造第二套匹配器**——宿主那一处 `includes` 才是权威口径，这里只是它的可测孪生）。
 * - 取**最长**命中的键；命中中文已在名字里 → 原样返回；无命中 → 原样返回（fail-visible，绝不猜）。
 */
export function glossName(name: string): string {
  if (!name) return name;
  for (const key of GLOSSARY_KEYS) {
    if (name.includes(key)) {
      const zh = ERAAV_NAME_GLOSSARY[key]!;
      if (name.includes(zh)) return name;
      return `${name}（${zh}）`;
    }
  }
  return name;
}
