/**
 * 错误摘要（宿主前端各处共一条口径）。
 *
 * 判据：`Error` 取 `message`，其余一律 `String()`。这条三元表达式在本仓曾以**两种变量名**
 * （`e` / `err`）手写 **89 次**（app/src 34 个文件），且内核里另有两份私有同名实现。
 * 抄散的后果不是"不优雅"，而是**同一个失败在不同面板上长成两样**：一处漏掉 `String()`
 * 兜底就成了 `[object Object]`，一处多打前缀就成了作者读不懂的栈串。
 *
 * 住契约层的理由与 `shortPath` 同一口径：纯字符串、零框架、零 DOM，插件面板与宿主都能吃，
 * 又不至于让插件为了一个小函数去 import 宿主（解耦审计 B/C 项）。
 *
 * 注意：本函数只负责**把 unknown 变成一句人读的话**，不负责决定要不要报、报给谁——
 * 静默吞异常仍是违反「内核不静默」铁律的行为，别用共享核把它包装得更顺手。
 */

/** 任意抛出值 → 一句可上屏的错误文本（无空格前缀、无栈、原样短句） */
export function errorText(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}
